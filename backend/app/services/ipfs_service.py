"""
IPFS Service
============

This module is responsible ONLY for communication with Kubo/IPFS.

Architecture:

    FastAPI
       |
       v
    IPFSService
       |
       v
    Kubo HTTP API
       |
       v
    IPFS Network
       |
       v
      CID

IMPORTANT:
-----------
This service does NOT contain:

- Blockchain logic
- Smart contract logic
- Database logic
- Frontend logic

Its only responsibility is interacting with IPFS/Kubo.
"""

from pathlib import Path
from typing import Union

import httpx


class IPFSService:
    """
    Service responsible for communicating with a Kubo IPFS node.

    We use asynchronous HTTP requests because our FastAPI
    application is asynchronous.
    """

    def __init__(
        self,
        api_url: str = "http://127.0.0.1:5001",
    ):
        """
        Initialize the IPFS service.

        Parameters
        ----------
        api_url:
            URL of the Kubo HTTP RPC API.

        Our local Kubo node currently exposes:

            http://127.0.0.1:5001
        """

        # Remove a trailing "/" if someone provides:
        #
        # http://127.0.0.1:5001/
        #
        # This prevents URLs such as:
        #
        # http://127.0.0.1:5001//api/v0/add
        self.api_url = api_url.rstrip("/")

        # Kubo endpoint used to add a file to IPFS.
        self.add_url = f"{self.api_url}/api/v0/add"

        # Kubo endpoint used to retrieve content using a CID.
        self.cat_url = f"{self.api_url}/api/v0/cat"

        # Kubo endpoint used to check whether
        # the IPFS node is running.
        self.id_url = f"{self.api_url}/api/v0/id"

    # ==========================================================
    # HEALTH CHECK
    # ==========================================================

    async def health_check(self) -> bool:
        """
        Check whether the Kubo node is reachable.

        Returns
        -------
        bool
            True  -> Kubo is running
            False -> Kubo cannot be reached

        Example:

            FastAPI
                |
                v
            IPFSService
                |
                v
            POST /api/v0/id
                |
                v
              Kubo
        """

        try:
            # AsyncClient is used instead of requests because
            # FastAPI endpoints are asynchronous.
            async with httpx.AsyncClient(
                timeout=5.0
            ) as client:

                response = await client.post(
                    self.id_url
                )

            # raise_for_status() raises an exception for
            # HTTP 4xx/5xx responses.
            response.raise_for_status()

            return True

        except httpx.HTTPError:
            # If Kubo is down or unreachable,
            # don't crash the application.
            return False

    # ==========================================================
    # FILE -> IPFS -> CID
    # ==========================================================

    async def upload_file(
        self,
        file_path: Union[str, Path],
    ) -> str:
        """
        Upload a single file to IPFS.

        Parameters
        ----------
        file_path:
            Path of the file that should be uploaded.

        Returns
        -------
        str
            CID generated by IPFS.

        Example:

            index.html
                |
                v
            IPFSService
                |
                v
              Kubo
                |
                v
              IPFS
                |
                v
               CID
        """

        # Convert string paths into Path objects.
        file_path = Path(file_path)

        # Before contacting IPFS, verify that the file exists.
        if not file_path.is_file():
            raise FileNotFoundError(
                f"File not found: {file_path}"
            )

        try:
            # Open the file in binary mode.
            #
            # "rb" is important because a website may contain:
            #
            # HTML
            # CSS
            # JavaScript
            # Images
            # Fonts
            # etc.
            #
            # Binary mode safely handles all of them.
            with file_path.open("rb") as file:

                # Create an asynchronous HTTP client.
                async with httpx.AsyncClient(
                    timeout=60.0
                ) as client:

                    # Send the file to Kubo's /add endpoint.
                    response = await client.post(
                        self.add_url,
                        files={
                            "file": (
                                file_path.name,
                                file,
                            )
                        },
                    )

            # Check whether Kubo returned an error.
            response.raise_for_status()

            # Kubo returns JSON.
            #
            # Example:
            #
            # {
            #     "Name": "index.html",
            #     "Hash": "bafy...",
            #     "Size": "1234"
            # }
            data = response.json()

            # The CID is returned in the "Hash" field.
            cid = data.get("Hash")

            # Never silently return None.
            # If Kubo didn't provide a CID,
            # something went wrong.
            if not cid:
                raise RuntimeError(
                    "Kubo did not return a CID"
                )

            return cid

        except httpx.HTTPError as error:

            # Convert the low-level HTTP error into
            # a meaningful application-level exception.
            raise RuntimeError(
                f"Failed to upload file to IPFS: {error}"
            ) from error

    # ==========================================================
    # DIRECTORY -> IPFS -> ROOT CID
    # ==========================================================

    async def upload_directory(
        self,
        directory_path: Union[str, Path],
    ) -> str:
        """
        Upload an entire website directory to IPFS.

        Returns the CID of the root directory.
        """

        directory_path = Path(directory_path)

        if not directory_path.is_dir():
            raise FileNotFoundError(
                f"Directory not found: {directory_path}"
            )

        file_handles = []

        try:
            params = {
                "recursive": "true",
                "wrap-with-directory": "true",
            }

            files = []

            for file_path in directory_path.rglob("*"):

                if not file_path.is_file():
                    continue

                relative_path = file_path.relative_to(
                    directory_path
                )

                file_handle = file_path.open("rb")
                file_handles.append(file_handle)

                files.append(
                    (
                        "file",
                        (
                            str(relative_path),
                            file_handle,
                        ),
                    )
                )

            if not files:
                raise ValueError(
                    "Website directory is empty"
                )

            async with httpx.AsyncClient(
                timeout=120.0
            ) as client:

                response = await client.post(
                    self.add_url,
                    params=params,
                    files=files,
                )

            response.raise_for_status()

            results = [
                line
                for line in response.text.splitlines()
                if line.strip()
            ]

            if not results:
                raise RuntimeError(
                    "Kubo returned an empty response"
                )

            import json

            root_data = json.loads(results[-1])

            root_cid = root_data.get("Hash")

            if not root_cid:
                raise RuntimeError(
                    "Kubo did not return a root CID"
                )

            return root_cid

        except httpx.HTTPError as error:

            raise RuntimeError(
                f"Failed to upload directory to IPFS: {error}"
            ) from error

        finally:
            # Always close all opened files,
            # even if the upload fails.
            for file_handle in file_handles:
                file_handle.close()        
    # ==========================================================
    # CID -> IPFS -> CONTENT
    # ==========================================================

    async def get_file(
        self,
        cid: str,
    ) -> bytes:
        """
        Retrieve file content from IPFS using a CID.

        Parameters
        ----------
        cid:
            Content Identifier of the IPFS object.

        Returns
        -------
        bytes
            Raw content stored at the CID.

        Example:

            CID
             |
             v
            Kubo
             |
             v
            IPFS
             |
             v
          File content
        """

        # Basic validation.
        #
        # We don't want to send an empty CID to Kubo.
        if not cid or not cid.strip():
            raise ValueError(
                "CID cannot be empty"
            )

        try:
            async with httpx.AsyncClient(
                timeout=60.0
            ) as client:

                response = await client.post(
                    self.cat_url,
                    params={
                        "arg": cid
                    },
                )

            response.raise_for_status()

            # response.content returns raw bytes.
            #
            # This is important because the content may be:
            #
            # HTML
            # CSS
            # JS
            # Image
            # PDF
            # etc.
            return response.content

        except httpx.HTTPError as error:

            raise RuntimeError(
                f"Failed to retrieve content from IPFS: {error}"
            ) from error


# ==============================================================
# REUSABLE SERVICE INSTANCE
# ==============================================================

# Instead of creating IPFSService every time,
# we create one reusable instance.
#
# Other backend modules can import:
#
#     from app.services.ipfs_service import ipfs_service
#
# and use:
#
#     await ipfs_service.upload_file(...)
#
#     await ipfs_service.get_file(...)
#
#     await ipfs_service.health_check()

ipfs_service = IPFSService()